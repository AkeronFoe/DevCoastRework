function getLanguage() {
    return localStorage.getItem(LANGUAGE_KEY) || DEFAULT_LANG
}

function normalizeKey(value) {
    return (value || '').toString().replace(/\s+/g, ' ').trim()
}

function translateText(value) {
    const lang = getLanguage()
    if (lang === DEFAULT_LANG) return value
    const map = TRANSLATIONS[lang] || {}
    const key = normalizeKey(value)
    return map[key] || value
}

function applyTranslations(lang) {
    const map = TRANSLATIONS[lang]
    if (!map) return

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            if (!node.nodeValue || !node.nodeValue.trim()) {
                return NodeFilter.FILTER_REJECT
            }
            const parent = node.parentElement
            if (!parent) return NodeFilter.FILTER_REJECT
            const tag = parent.tagName
            if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') {
                return NodeFilter.FILTER_REJECT
            }
            return NodeFilter.FILTER_ACCEPT
        }
    })

    while (walker.nextNode()) {
        const node = walker.currentNode
        const raw = node.nodeValue
        const key = normalizeKey(raw)
        const translated = map[key]
        if (!translated) continue
        const leading = raw.match(/^\s*/)[0]
        const trailing = raw.match(/\s*$/)[0]
        node.nodeValue = `${leading}${translated}${trailing}`
    }

    document.querySelectorAll('[placeholder]').forEach((el) => {
        const raw = el.getAttribute('placeholder')
        const translated = map[normalizeKey(raw)]
        if (translated) {
            el.setAttribute('placeholder', translated)
        }
    })

    document.querySelectorAll('[aria-label]').forEach((el) => {
        const raw = el.getAttribute('aria-label')
        const translated = map[normalizeKey(raw)]
        if (translated) {
            el.setAttribute('aria-label', translated)
        }
    })
}

window.translateText = translateText

document.addEventListener('DOMContentLoaded', () => {
    const lang = getLanguage()
    document.documentElement.setAttribute('lang', lang)

    const langSelect = document.getElementById('lang-select')
    if (langSelect) {
        langSelect.value = lang
        langSelect.addEventListener('change', (event) => {
            localStorage.setItem(LANGUAGE_KEY, event.target.value)
            window.location.reload()
        })
    }

    if (lang !== DEFAULT_LANG) {
        applyTranslations(lang)
    }
})
